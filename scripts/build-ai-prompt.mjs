import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const PROMPT_SOURCES = [
  "src/ai/system-runtime.md",
  ".agents/skills/write-motionly/SKILL.md",
];
export const PROMPT_OUTPUT = "src/ai/generated/prompt.ts";

// Git may check out CRLF on Windows. Neither line endings nor a BOM should
// change the deployed prompt version. No timestamps or machine paths are used.
export function normalizeSource(source) {
  return (
    source
      .replace(/^\uFEFF/, "")
      .replace(/\r\n?/g, "\n")
      .trimEnd() + "\n"
  );
}

export function compilePrompt(sources) {
  const normalized = sources.map(({ path, content }) => ({
    path,
    content: normalizeSource(content),
  }));
  const hash = createHash("sha256")
    .update(JSON.stringify(normalized))
    .digest("hex");
  const prompt = normalized
    .map(({ path, content }) => {
      const body = path.endsWith("SKILL.md")
        ? content.replace(/^---\n[\s\S]*?\n---\n/, "").trim()
        : content.trim();
      return `SOURCE: ${path}\n${body}`;
    })
    .join("\n\n");
  return [
    "// Generated by scripts/build-ai-prompt.mjs. Do not edit by hand.",
    "// Regenerate: npm run prompt:build; verify: npm run prompt:check.",
    `export const MOTIONLY_PROMPT_SOURCES = ${JSON.stringify(normalized.map((source) => source.path))} as const;`,
    `export const MOTIONLY_PROMPT_HASH = ${JSON.stringify(hash)};`,
    `export const MOTIONLY_SYSTEM_PROMPT = ${JSON.stringify(`MOTIONLY PROMPT VERSION (sha256): ${hash}\n\n${prompt}`)};`,
    "",
  ].join("\n");
}

export async function buildPrompt({ root = projectRoot, check = false } = {}) {
  const sources = await Promise.all(
    PROMPT_SOURCES.map(async (path) => ({
      path,
      content: await readFile(resolve(root, path), "utf8"),
    })),
  );
  const artifact = compilePrompt(sources);
  const output = resolve(root, PROMPT_OUTPUT);
  let existing;
  try {
    existing = normalizeSource(await readFile(output, "utf8"));
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  if (existing === artifact) return { changed: false, output };
  if (check) {
    throw new Error(
      `${PROMPT_OUTPUT} is missing or stale. Run npm run prompt:build and commit the generated artifact.`,
    );
  }
  await mkdir(dirname(output), { recursive: true });
  await writeFile(output, artifact, "utf8");
  return { changed: true, output };
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(resolve(process.argv[1])).href
) {
  const args = process.argv.slice(2);
  try {
    if (args.some((arg) => arg !== "--check"))
      throw new Error("Usage: node scripts/build-ai-prompt.mjs [--check]");
    const result = await buildPrompt({ check: args.includes("--check") });
    console.log(
      result.changed
        ? `Generated ${PROMPT_OUTPUT}`
        : "AI prompt is up to date.",
    );
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
